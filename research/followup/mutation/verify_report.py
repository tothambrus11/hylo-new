"""Tables for the additional measurements (verify.jsonl, fullnoabs.jsonl); writes verify.md.

Usage: python3 verify_report.py
"""
import collections, hashlib, json, os, statistics
import tc, run, mutate
from analyse import clopper_pearson, cluster_bootstrap, pct

def load(name):
    p = os.path.join(tc.HERE, name)
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []

def cell(x):
    if x is None: return "–"
    if x["status"] == "timeout": return f"timeout ({x['wall']:.0f} s)"
    if x["status"] != "ok": return f"abort at {x.get('maxrss_mb', '?')} MB resident ({x['wall']:.0f} s)"
    return f"{x['matches']:,} ({x['ms'] / 1000:.1f} s, {x.get('maxrss_mb', '?')} MB)" if x["ms"] >= 1000 else f"{x['matches']:,} ({x['ms']:.0f} ms)"

def main():
    out = []; P = out.append
    C = {r["id"]: r for r in load("classified.jsonl")}
    M = {m["id"]: m for m in run.load_mutants()}
    R = collections.defaultdict(dict)
    for r in load("results.jsonl"): R[r["id"]][r["config"]] = r
    V = []
    seen = set()
    for v in load("verify.jsonl"):      # the sets basecap2 and bigcap were run twice; the first row of each point is used
        k = (v["set"], v["id"], v["what"], v["config"], v["depth"], v["rep"])
        if k not in seen: seen.add(k); V.append(v)
    def kind(i):
        c = C[i]
        if c["cls"] == "equivalent": return "wrong" if c["full"]["diags"] > 0 else "valid"
        return {"rejected": "rejected", "crash": "blowup", "timeout": "blowup", "syntax": "syntax"}[c["cls"]]
    def digest(i):
        m = M[i]
        if m["group"] == "stdlib": return i
        return hashlib.md5(mutate.apply(open(run.source_path(m)).read(), m).encode()).hexdigest()

    P("# Additional measurements (generated by verify_report.py)\n")

    # 1. reproduction
    P("## 1. Re-runs compared with the recorded rows\n")
    n = bad = 0
    for v in V:
        if v["set"] not in ("sample",) or v["what"] != "mutant": continue
        r = R[v["id"]][v["config"]]
        if r["status"] != "ok":      # aborted at the 1 GB cap in the main run: compare with the 2.5 GB recheck
            r = next((x for x in load("recheck.jsonl") if (x["id"], x["config"]) == (v["id"], v["config"])), r)
        n += 1
        same = (v["status"], v["diags"], v["matches"], v["subgoals"]) == (r["status"], r["diags"], r["matches"], r["subgoals"])
        if not same:
            bad += 1; P(f"- differs: {v['id']} {v['config']}: recorded {r['status']} {r['diags']} {r['matches']}, re-run {v['status']} {v['diags']} {v['matches']}")
    P(f"{n} (mutant, configuration) points re-run with the default 2.5 GB cap; {bad} differ from `results.jsonl` in status, number of diagnostics, `summon.matches` or `summon.subgoals`.\n")

    # 2. duplicates
    P("## 2. Identical programs in the sample\n")
    src = collections.defaultdict(set)
    for m in M.values():
        if m["group"] != "stdlib": src[hashlib.md5(open(run.source_path(m), "rb").read()).hexdigest()].add(m["file"])
    nfiles = sum(len(v) for v in src.values())
    P(f"User source files with mutants: {nfiles}; distinct contents: {len(src)} (the standard library adds {len({m['file'] for m in M.values() if m['group'] == 'stdlib'})} files).\n")
    P("| class | mutants | distinct mutated programs |")
    P("|---|---:|---:|")
    for k in ("rejected", "blowup", "wrong", "valid"):
        ids = [i for i in M if kind(i) == k]
        P(f"| {k} | {len(ids)} | {len({digest(i) for i in ids})} |")
    P("")
    def sdig(i):
        m = M[i]
        return m["file"] if m["group"] == "stdlib" else hashlib.md5(open(run.source_path(m), "rb").read()).hexdigest()
    for k in ("rejected", "blowup", "wrong"):
        ids = [i for i in M if kind(i) == k]
        P(f"- {k}: {len({M[i]['file'] for i in ids})} source files, {len({sdig(i) for i in ids})} distinct contents.")
    P("")
    import re
    eqc = {}
    def has_eq(i):
        p = run.source_path(M[i])
        if p not in eqc: eqc[p] = bool(re.search(r"where[^{}()\n]*==", mutate.mask(open(p).read())))
        return eqc[p]
    P("Outcome under base of the mutants of sources with an equality requirement, by operator:\n")
    P("| operator | ill-typed | rejected normally | not finished within 2.5 GB, or 31 s and more | wrongly accepted | still valid |")
    P("|---|---:|---:|---:|---:|---:|")
    t = collections.defaultdict(collections.Counter)
    for i in M:
        if not has_eq(i) or kind(i) == "syntax": continue
        op = M[i]["op"]
        if op == "del-where-req": op += " (an equality)" if "==" in M[i]["orig"] else " (a conformance)"
        t[op][kind(i)] += 1
    for op, c in sorted(t.items()):
        P(f"| {op} | {c['rejected'] + c['blowup'] + c['wrong']} | {c['rejected']} | {c['blowup']} | {c['wrong']} | {c['valid']} |")
    P("")

    # 3. depth dependence of the blow-ups
    P("## 3. The blow-ups as a function of the depth bound\n")
    P("`summon.matches` (typing time, peak resident memory). 2.5 GB cap on the address space, 150 s timeout. Depth 10 is the default.\n")
    d = collections.defaultdict(dict)
    for v in V:
        if v["set"] == "depthblow": d[(v["id"], v["config"])][v["depth"]] = v
        if v["set"] == "basecap" and v["id"] in ("tests/repl-typearg/007", "corpus/del-where-req/013") and v["config"] == "base": d[(v["id"], "base")][10] = v
    for r in load("recheck.jsonl"):
        if (r["id"], r["config"]) in d: d[(r["id"], r["config"])].setdefault(10, dict(r, maxrss_mb="?"))
    P("| mutant | config | depth 6 | 7 | 8 | 9 | 10 |")
    P("|---|---|---:|---:|---:|---:|---:|")
    for (i, c), cells in d.items():
        P(f"| {i} | {c} | " + " | ".join(cell(cells.get(k)) for k in (6, 7, 8, 9, 10)) + " |")
    P("")

    # 4. FULL depth
    P("## 4. Ill-typed mutants that reach the depth bound under FULL\n")
    d = collections.defaultdict(dict)
    for v in V:
        if v["set"] == "depthfull": d[(v["id"], v["config"])][v["depth"]] = v
    P("| mutant | config | depth 10 | 12 | 14 | depthExhausted |")
    P("|---|---|---:|---:|---:|---:|")
    for (i, c), cells in d.items():
        P(f"| {i} | {c} | " + " | ".join(cell(cells.get(k)) for k in (10, 12, 14)) + f" | {cells[10]['depthExhausted']} |")
    P("")

    # 5. caps
    P("## 5. Cells that aborted under a reduced memory cap, re-run with the default 2.5 GB cap\n")
    P("| mutant | config | result |")
    P("|---|---|---|")
    for v in V:
        if v["set"] in ("capcheck", "basecap", "basecap2", "eqsolvecap", "bigcap"):
            res = f"rejected, {v['diags']} diagnostics, {cell(v)}" if v["status"] == "ok" and v["diags"] else "accepted" if v["status"] == "ok" else cell(v)
            P(f"| {v['id']} | {v['config']}" + (" (5 GB cap)" if v["set"] == "bigcap" else "") + f" | {res} |")
    P("")
    bc = [v for v in V if v["set"] in ("basecap", "basecap2") and v["config"] == "base"]
    P(f"Base at the 2.5 GB cap: {len(bc)} blow-ups run here, {sum(v['status'] == 'ok' for v in bc)} finish, {sum(v['status'] != 'ok' for v in bc)} abort "
      f"(peak resident memory {min(v['maxrss_mb'] for v in bc if v['status'] != 'ok')} to {max(v['maxrss_mb'] for v in bc if v['status'] != 'ok')} MB). "
      "`corpus/del-where-req/009` is in `recheck.jsonl` (finishes); `tests/del-where-req/019` is the same program as `workloads/del-where-req/016`.\n")

    # 5b. attribution of the wrong acceptances
    aw = collections.defaultdict(dict)
    for v in V:
        if v["set"] == "attribwrong": aw[v["config"]][v["id"]] = v
    if aw:
        P("## 5b. The 29 mutants that base accepts and FULL rejects, under MIN5 plus individual fixes (2.5 GB cap, 60 s)\n")
        P("| configuration | rejected | of which with more diagnostics than FULL | still accepted | abort at the cap | `summon.matches` when rejected | typing time when rejected |")
        P("|---|---:|---:|---:|---:|---|---|")
        for c, d in aw.items():
            rej = [x for x in d.values() if x["status"] == "ok" and x["diags"] > 0]
            acc = [i for i, x in d.items() if x["status"] == "ok" and x["diags"] == 0]
            more = sum(x["diags"] > R[i]["full"]["diags"] for i, x in d.items() if x["status"] == "ok" and x["diags"] > 0)
            m = sorted(x["matches"] for x in rej); t = sorted(x["ms"] for x in rej)
            P(f"| {c} | {len(rej)} | {more} | {len(acc)} | {sum(x['status'] != 'ok' for x in d.values())} | {m[0]:,} to {m[-1]:,} (median {m[len(m) // 2]:,}; {sum(y >= 10000 for y in m)} at 10,000 or more) | {t[0]:.0f} ms to {t[-1] / 1000:.1f} s |")
        P("")
        for c, d in aw.items():
            acc = sorted(i for i, x in d.items() if x["status"] == "ok" and x["diags"] == 0)
            bad = sorted(i for i, x in d.items() if x["status"] != "ok")
            if acc and len(acc) <= 6: P(f"- {c}: still accepted: {', '.join(acc)}.")
            if bad: P(f"- {c}: abort at the cap: {', '.join(bad)}.")
        P("")

    # 6. interleaved timing
    P("## 6. Typing time of the unmutated source and of the mutant, run alternately (ms, five runs each)\n")
    t = collections.defaultdict(list)
    for v in V:
        if v["set"] == "timing" and v["status"] == "ok": t[(v["id"], v["config"], v["what"])].append(v["ms"])
    P("| mutant | config | unmutated: min / median | mutant: min / median | ratio of minima | ratio recorded in the main run |")
    P("|---|---|---:|---:|---:|---:|")
    for (i, c, w) in list(t):
        if w != "original": continue
        a, b = t[(i, c, "original")], t.get((i, c, "mutant"), [])
        if not b: continue
        P(f"| {i} | {c} | {min(a):.0f} / {statistics.median(a):.0f} | {min(b):.0f} / {statistics.median(b):.0f} | {min(b) / min(a):.2f} | {C[i]['rt_' + c]:.2f} |")
    P("")

    # 7. FULL versus FULL without the model
    F = load("fullnoabs.jsonl")
    if sum(r["kind"] == "mutant" for r in F) >= 50:
        P("## 7. The abstract model with the equality fixes in place: FULL versus FULL without `absmodel,absquotient`\n")
        fm = {r["id"]: r for r in F if r["kind"] == "mutant"}
        fs = {r["file"]: r for r in F if r["kind"] == "source"}
        ill = [i for i in M if kind(i) in ("rejected", "blowup", "wrong") and i in fm]
        P(f"Ill-typed mutants run: {len(ill)} of {sum(kind(i) in ('rejected', 'blowup', 'wrong') for i in M)}; all mutants run: {len(fm)}.\n")
        st = collections.Counter(fm[i]["status"] for i in fm)
        P(f"Status under FULL without the model, all mutants: {dict(st)}.\n")
        dv = [i for i in fm if (fm[i]["status"], fm[i]["diags"]) != (R[i]["full"]["status"], R[i]["full"]["diags"])]
        dt = [i for i in fm if i not in dv and fm[i]["msgs"] != R[i]["full"]["msgs"]]
        P(f"Differences from FULL in verdict or number of diagnostics: {len(dv)}" + (": " + ", ".join(dv) if dv else "") + f". Differences in the text of the diagnostics only: {len(dt)}" + (": " + ", ".join(dt[:20]) if dt else "") + ".\n")
        g = lambda i: fm[i]["matches"] / max(1, R[i]["full"]["matches"])
        sv = lambda i: fm[i]["matches"] - R[i]["full"]["matches"]
        def srckey(i): return "<stdlib>" if M[i]["group"] == "stdlib" else M[i]["file"]
        def inherited(i):
            s = fs.get(srckey(i)); 
            return s is not None and s["matches"] / max(1, C[i]["orig_full"]["matches"]) > 10
        okk = [i for i in ill if fm[i]["status"] == "ok" and R[i]["full"]["status"] == "ok"]
        rows = [
            ("`summon.matches` ratio above 10", lambda i: g(i) > 10),
            ("– and the unmutated source does not already have a ratio above 10", lambda i: g(i) > 10 and not inherited(i)),
            ("– and at least 1,000 matches without the model", lambda i: g(i) > 10 and fm[i]["matches"] >= 1000),
            ("`summon.subgoals` ratio above 10", lambda i: fm[i]["subgoals"] / max(1, R[i]["full"]["subgoals"]) > 10),
        ]
        P("| measure of \"more than 10× cheaper with the model\" | mutants | of | share | exact 95% interval | interval resampling source files |")
        P("|---|---:|---:|---:|---|---|")
        for name, pred in rows:
            k = sum(pred(i) for i in okk); lo, hi = clopper_pearson(k, len(okk)); blo, bhi = cluster_bootstrap(okk, pred, lambda i: M[i]["file"])
            P(f"| {name} | {k} | {len(okk)} | {pct(k / len(okk))} | {pct(lo)} – {pct(hi)} | {pct(blo)} – {pct(bhi)} |")
        P("")
        s = sorted(sv(i) for i in okk)
        P(f"Matches saved by the model (FULL without the model minus FULL), ill-typed mutants: minimum {s[0]}, median {statistics.median(s)}, p99 {s[int(len(s) * .99)]}, maximum {s[-1]}. "
          f"Mutants where the model increases `summon.matches`: {sum(x < 0 for x in s)}.\n")
        P("By class:\n")
        P("| class | n | ratio above 10 | largest saving (matches) | largest cost without the model (matches) |")
        P("|---|---:|---:|---:|---:|")
        for k in ("rejected", "blowup", "wrong"):
            ids = [i for i in okk if kind(i) == k]
            if ids: P(f"| {k} | {len(ids)} | {sum(g(i) > 10 for i in ids)} | {max(sv(i) for i in ids)} | {max(fm[i]['matches'] for i in ids)} |")
        P("")
        P("Largest savings:\n")
        P("| mutant | source | class | FULL without the model | FULL | saved |")
        P("|---|---|---|---:|---:|---:|")
        for i in sorted(okk, key=lambda i: -sv(i))[:10]:
            P(f"| {i} | `{os.path.basename(M[i]['file'])}` | {kind(i)} | {fm[i]['matches']} | {R[i]['full']['matches']} | {sv(i)} |")
        P("")
        # the MIN5 literal criterion, on distinct programs
        rej = [i for i in M if kind(i) == "rejected"]
        lit = [i for i in rej if R[i]["min5"]["matches"] / max(1, R[i]["min5abs"]["matches"]) > 10]
        P(f"For comparison, the literal criterion on MIN5 (113 of 670) counted on distinct mutated programs: {len({digest(i) for i in lit})} of {len({digest(i) for i in rej})}.\n")
    open(os.path.join(tc.HERE, "verify.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))

if __name__ == "__main__":
    main()
