OPCHARS = set("-+*/%<>=!&|^~?.")

def cut_swiftlike(d, lang):
    """Swift and the original Hylo: `kw Name<Params>: Inherits (sig) where Reqs`."""
    h, kw = d["head"], d["kw"]
    i = len(h) - len(h.lstrip())
    name = ""
    if kw in ("init", "subscript") and not re.match(r"[A-Za-z_]", h[i:i + 1] or " "):
        name = kw
        if h[i:i + 1] in ("?", "!"): i += 1
    elif kw in ("func", "fun") and h[i:i + 1] in OPCHARS:
        j = i
        while j < len(h) and h[j] in OPCHARS: j += 1
        name, i = h[i:j], j
    else:
        m = re.match(r"(?:infix|prefix|postfix)[-+*/%<>=!&|^~?.]+|`?[A-Za-z_][\w.]*`?", h[i:])
        if m:
            name, i = m.group(0), i + m.end()
            if kw == "extension" or kw == "conformance":            # the extended type may have arguments
                k = i
                while k < len(h) and h[k] == " ": k += 1
                if h[k:k + 1] == "<":
                    k2 = angle_group(h, k); name += nows(h[k:k2]); i = k2
                    m2 = re.match(r"\.[\w.]+", h[i:])
                    if m2: name += m2.group(0); i += m2.end()
        elif kw == "extension" and h[i:i + 1] == "[":
            j = paren_group(h, i); name, i = nows(h[i:j]), j
    j = i
    while j < len(h) and h[j] in " \n": j += 1
    generics = ""
    if h[j:j + 1] == "<" and kw not in ("extension", "conformance"):
        k = angle_group(h, j); generics, i = h[j + 1:k - 1], k
    rest = h[i:]
    w = find_top(rest, "where")
    where = rest[w + 5:] if w >= 0 else ""
    sig = rest[:w] if w >= 0 else rest
    inherits = ""
    if kw not in ("func", "fun", "init", "subscript", "property", "typealias"):
        s2 = sig.lstrip()
        if s2.startswith(":"):
            inherits = s2[1:]
            eq = find_top_char(inherits, "=")
            if eq >= 0: inherits = inherits[:eq]
            sig = ""
    return name, generics, inherits, sig, where

def find_top_char(s, ch):
    depth = 0
    for i, c in enumerate(s):
        if c in OPEN: depth += 1
        elif c in CLOSE: depth = max(0, depth - 1)
        elif depth == 0 and c == ch and s[i:i + 2] != "==" and (i == 0 or s[i - 1] not in "=!<>"): return i
    return -1

def reqs_swiftlike(generics, where, sig, protocols):
    """Returns (parameter names, requirements).  A requirement is a dict with keys kind/via and
    either subj/bound (conformance) or lhs/rhs (equality)."""
    params, reqs = [], []
    for p in split_top(generics, ","):
        p = ws(p)
        if not p: continue
        p = re.sub(r"^(each|repeat)\s+", "", p)
        if p.startswith("let ") or p.startswith("@"):
            reqs.append({"kind": "value", "via": "inline", "text": p}); continue
        parts = split_top(p, ":")
        nm = ws(parts[0])
        params.append(nm)
        if len(parts) > 1:
            add_bounds(reqs, nm, ":".join(parts[1:]), "inline", protocols)
    for r in split_top(where, ","):
        r = ws(r)
        if not r: continue
        r = re.sub(r"^(repeat\s+)?(each\s+)?", "", r)
        eq = split_top(r, "==")
        if len(eq) == 2:
            reqs.append({"kind": "eq", "via": "where", "lhs": nows(eq[0]), "rhs": nows(eq[1])}); continue
        parts = split_top(r, ":")
        if len(parts) >= 2:
            add_bounds(reqs, nows(parts[0]), ":".join(parts[1:]), "where", protocols)
        else:
            reqs.append({"kind": "other", "via": "where", "text": r})
    # opaque parameter types with primary associated types: `some Collection<Int>`
    for m in re.finditer(r"\b(some|any)\s+([A-Z]\w*)\s*<", sig):
        k = angle_group(sig, m.end() - 1)
        args = split_top(sig[m.end():k - 1], ",")
        prim = protocols.get(m.group(2), {}).get("primary", [])
        for n, a in enumerate(args):
            an = prim[n] if n < len(prim) else "#%d" % n
            reqs.append({"kind": "eq", "via": "primary", "lhs": "<opaque %s@%d>.%s" % (m.group(2), m.start(), an), "rhs": nows(a)})
    return params, reqs

def add_bounds(reqs, subj, bound_text, via, protocols):
    for b in split_top(bound_text, "&"):
        b = ws(b)
        if not b: continue
        if b.startswith("~"):
            reqs.append({"kind": "inverse", "via": via, "subj": subj, "bound": b}); continue
        if b in ("AnyObject", "_NativeClass", "_Trivial", "_RefCountedObject", "_Class", "_BitwiseCopyable") or b.startswith("_Trivial"):
            reqs.append({"kind": "layout", "via": via, "subj": subj, "bound": b}); continue
        base = b
        m = re.match(r"([\w.]+)\s*<", b)
        if m:
            base = m.group(1)
            k = angle_group(b, m.end() - 1)
            if base.split(".")[-1] in protocols:      # primary associated types: P<A, B>
                prim = protocols[base.split(".")[-1]].get("primary", [])
                for n, a in enumerate(split_top(b[m.end():k - 1], ",")):
                    an = prim[n] if n < len(prim) else "#%d" % n
                    reqs.append({"kind": "eq", "via": "primary", "lhs": subj + "." + an, "rhs": nows(a)})
        reqs.append({"kind": "conf", "via": via, "subj": subj, "bound": base})

def cut_hylonew(d):
    """The new Hylo syntax: `kw [name :] [<Params where Reqs>] [=>] Name[<Args>] [is P] ...`."""
    h, kw = d["head"], d["kw"]
    i = len(h) - len(h.lstrip())
    name, generics, where, inherits = "", "", "", ""
    if kw in ("given", "extension"):
        m = re.match(r"([A-Za-z_]\w*)\s*:\s*", h[i:])         # named given
        if kw == "given" and m and not re.match(r"[A-Za-z_]\w*\s*:\s*:", h[i:]): i += m.end()
        if h[i:i + 1] == "<":
            k = angle_group(h, i); generics, i = h[i + 1:k - 1], k
        rest = h[i:].lstrip()
        if rest.startswith("=>"): rest = rest[2:]
        if kw == "given":
            parts = re.split(r"\bis\b", rest, maxsplit=1)
            name = nows(parts[0])
            inherits = parts[1] if len(parts) > 1 else ""
            if "=" in name and len(parts) == 1:               # `given Void = ()`: a value given
                name = nows(rest.split("=")[0])
        else:
            name = nows(rest)
        sig = ""
    else:
        if kw in ("init", "subscript") and not re.match(r"[A-Za-z_]", h[i:i + 1] or " "):
            name = kw
        else:
            m = re.match(r"(?:infix|prefix|postfix)[-+*/%<>=!&|^~?.]+|[A-Za-z_]\w*", h[i:])
            if m: name, i = m.group(0), i + m.end()
        if h[i:i + 1] == "<":
            k = angle_group(h, i); generics, i = h[i + 1:k - 1], k
        sig = h[i:]
        if kw in ("struct", "enum", "trait"):
            m = re.match(r"\s*(is|refines)\b", sig)
            if m: inherits, sig = sig[m.end():], ""
    w = find_top(generics, "where")
    if w >= 0: generics, where = generics[:w], generics[w + 5:]
    return name, generics, inherits, sig, where

def reqs_hylonew(generics, where):
    params, reqs = [], []
    def req(r, via):
        r = ws(r)
        if not r: return
        if r.startswith("let "):
            reqs.append({"kind": "value", "via": via, "text": r}); return
        eq = split_top(r, "==")
        if len(eq) == 2:
            reqs.append({"kind": "eq", "via": via, "lhs": nows(eq[0]), "rhs": nows(eq[1])}); return
        m = re.search(r"\bis\b", r)
        if m:
            subj = nows(r[:m.start()])
            for b in split_top(r[m.end():], "&"):
                b = ws(b)
                reqs.append({"kind": "conf", "via": via, "subj": subj, "bound": b})
            return
        reqs.append({"kind": "other", "via": via, "text": r})
    for p in split_top(generics, ","):
        p = ws(p)
        if not p: continue
        m = re.match(r"([A-Za-z_]\w*)\s*(.*)$", p)
        if not m: continue
        params.append(m.group(1))
        if m.group(2): req(p, "inline")
    for r in split_top(where, ","):
        req(r, "where")
    return params, reqs

# --- Rust -------------------------------------------------------------------------------------

def rust_path(t):
    """Normalises a Rust type path: `<A as T>::B` -> `A.B`, `A::B` -> `A.B`."""
    t = nows(t)
    prev = None
    while prev != t:
        prev = t
        t = re.sub(r"<([^<>]*?)as[A-Za-z_][^<>]*(?:<[^<>]*>)?>::", lambda m: m.group(1) + ".", t)
    return t.replace("::", ".")

def cut_rust(d):
    h, kw = d["head"], d["kw"]
    i = len(h) - len(h.lstrip())
    name, generics, inherits = "", "", ""
    if kw == "impl":
        if h[i:i + 1] == "<":
            k = angle_group(h, i); generics, i = h[i + 1:k - 1], k
        rest = h[i:]
        w = find_top(rest, "where")
        where = rest[w + 5:] if w >= 0 else ""
        body = rest[:w] if w >= 0 else rest
        f = find_top(body, "for")
        if f >= 0:
            inherits, name = ws(body[:f]), ws(body[f + 3:])
        else:
            name = ws(body)
        return name, generics, inherits, "", where
    m = re.match(r"[A-Za-z_]\w*", h[i:])
    if m: name, i = m.group(0), i + m.end()
    if h[i:i + 1] == "<":
        k = angle_group(h, i); generics, i = h[i + 1:k - 1], k
    rest = h[i:]
    w = find_top(rest, "where")
    where = rest[w + 5:] if w >= 0 else ""
    sig = rest[:w] if w >= 0 else rest
    if kw in ("trait", "type"):
        s2 = sig.lstrip()
        if s2.startswith(":"):
            inherits = s2[1:]
            eq = find_top_char(inherits, "=")
            if eq >= 0: inherits = inherits[:eq]
            sig = ""
    return name, generics, inherits, sig, where

FN_SUGAR = re.compile(r"^(?:Async)?Fn(?:Mut|Once)?\s*\(")

def rust_bounds(reqs, subj, text, via):
    for b in split_top(text, "+"):
        b = ws(b)
        b = re.sub(r"^for\s*<[^>]*>\s*", "", b)
        b = re.sub(r"^(\[const\]|~const|const)\s+", "", b)
        if not b: continue
        if b.startswith("'"): reqs.append({"kind": "lifetime", "via": via, "subj": subj, "bound": b}); continue
        if b.startswith("?") or b.startswith("!"): reqs.append({"kind": "inverse", "via": via, "subj": subj, "bound": b}); continue
        if b.startswith("use<"): continue
        if FN_SUGAR.match(b):
            k = paren_group(b, b.index("("))
            base = b[:b.index("(")].strip()
            reqs.append({"kind": "conf", "via": via, "subj": subj, "bound": base})
            tail = b[k:].strip()
            if tail.startswith("->"):
                reqs.append({"kind": "eq", "via": "fnsugar", "lhs": subj + ".Output", "rhs": rust_path(tail[2:])})
            continue
        m = re.match(r"([\w:]+)\s*<", b)
        base = b
        if m:
            base = m.group(1)
            k = angle_group(b, m.end() - 1)
            for a in split_top(b[m.end():k - 1], ","):
                a = ws(a)
                e = split_top(a, "=")
                if len(e) == 2 and re.match(r"^[A-Za-z_]\w*(<[^=]*>)?$", ws(e[0])):
                    an = re.match(r"\w+", ws(e[0])).group(0)
                    reqs.append({"kind": "eq", "via": "binding", "lhs": subj + "." + an, "rhs": rust_path(e[1])})
                    continue
                c = split_top(a, ":")
                if len(c) == 2 and re.match(r"^[A-Za-z_]\w*$", ws(c[0])):     # associated type bound
                    rust_bounds(reqs, subj + "." + ws(c[0]), c[1], "assocbound")
        reqs.append({"kind": "conf", "via": via, "subj": subj, "bound": base.split("::")[-1]})

def reqs_rust(generics, where, sig, kw):
    params, reqs = [], []
    for p in split_top(generics, ","):
        p = ws(p)
        if not p or p.startswith("'"): continue
        if p.startswith("const "):
            reqs.append({"kind": "value", "via": "inline", "text": p}); continue
        p = split_top(p, "=")[0]                    # default
        parts = split_top(p, ":")
        nm = ws(parts[0])
        params.append(nm)
        if len(parts) > 1: rust_bounds(reqs, nm, ":".join(parts[1:]), "inline")
    for r in split_top(where, ","):
        r = ws(r)
        r = re.sub(r"^for\s*<[^>]*>\s*", "", r)
        if not r or r.startswith("'"): continue
        parts = split_top(r, ":")
        if len(parts) >= 2: rust_bounds(reqs, rust_path(parts[0]), ":".join(parts[1:]), "where")
        else: reqs.append({"kind": "other", "via": "where", "text": r})
    # `impl Trait<A = T>` and `dyn Trait<A = T>` in the signature
    for m in re.finditer(r"\b(impl|dyn)\s+", sig):
        j = m.end(); depth = 0; k = j
        while k < len(sig):
            c = sig[k]
            if sig[k:k + 2] == "->": k += 2; continue
            if c in "(<[": depth += 1
            elif c in ")>]":
                if depth == 0: break
                depth -= 1
            elif c == "," and depth == 0: break
            k += 1
        tmp = []
        rust_bounds(tmp, "<opaque@%d>" % m.start(), sig[j:k], "opaque")
        reqs.extend(tmp)
    return params, reqs

