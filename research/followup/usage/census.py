FUNC_KW = {"func", "fun", "fn", "init", "subscript", "property"}
TYPE_KW = {"struct", "class", "enum", "actor", "union"}

def build(codebase, lang, roots, suffixes):
    files = []
    for root in roots:
        for dp, dn, fn in os.walk(root):
            dn.sort()
            for f in sorted(fn):
                if f.endswith(suffixes): files.append(os.path.join(dp, f))
    groups, nlines = [], {}
    for path in files:
        raw, n = scan_file(path, lang, codebase)
        rel = os.path.relpath(path, os.path.commonpath(roots) if len(roots) > 1 else roots[0])
        nlines[rel] = n
        decls = []
        groups.append(decls)
        for r in raw:
            kw = r["kw"]
            if lang == "rust": name, generics, inherits, sig, where = cut_rust(r)
            elif lang == "hylonew": name, generics, inherits, sig, where = cut_hylonew(r)
            else: name, generics, inherits, sig, where = cut_swiftlike(r, lang)
            decls.append({"file": rel, "line": r["line"], "kw": kw, "name": name, "generics": ws(generics),
                          "inherits": ws(inherits), "sig": ws(sig), "where": ws(where),
                          "_parent": None if r["parent"] is None else decls[r["parent"]], "has_body": r["has_body"]})
    return groups, nlines

def kind_of(d, lang):
    kw = d["kw"]
    par = d["_parent"]
    if kw in FUNC_KW: return "function"
    if kw in TYPE_KW: return "type"
    if kw in ("protocol", "trait"): return "trait"
    if kw == "extension": return "extension"
    if kw in ("conformance", "given"): return "conformance"
    if kw == "impl": return "conformance" if d["inherits"] else "extension"
    if kw == "associatedtype": return "assoctype"
    if kw == "typealias": return "alias"
    if kw == "namespace": return "namespace"
    if kw == "type":
        if par is not None and par["kw"] in ("trait",):
            return "assoctype"
        if lang == "hyloold": return "type" if d["has_body"] else "alias"
        if lang == "rust":
            return "alias"                            # includes associated type definitions in impls
        return "alias"
    return kw

def tables(decls, lang):
    """Name tables: generic parameters of each nominal type; associated types and refinements of each trait."""
    gtypes, traits = collections.defaultdict(set), {}
    for d in decls:
        k = d["kind"]
        if k == "type" or k == "alias":
            ps = [ws(split_top(re.sub(r"^(each|repeat|const)\s+", "", ws(p)), ":")[0]) for p in split_top(d["generics"], ",") if ws(p)]
            if lang == "hylonew": ps = [re.match(r"\w*", p).group(0) for p in ps]
            gtypes[d["name"]].update(p for p in ps if p and not p.startswith("'"))
            gtypes[d["name"]].update(())
        if k == "trait":
            t = traits.setdefault(d["name"], {"assoc": [], "refines": [], "primary": [], "decl": None})
            sep = "+" if lang == "rust" else ("&" if lang == "hylonew" else ",")
            inh = d["inherits"]
            if lang == "hylonew": inh = inh.replace(",", "&")
            t["refines"] += [re.match(r"[\w.]*", ws(x).split("::")[-1]).group(0) for x in split_top(inh, sep) if ws(x)]
            if lang == "swift" and d["generics"]: t["primary"] = [ws(x) for x in d["generics"].split(",")]
    for d in decls:
        if d["kind"] == "assoctype" and d["_parent"] is not None:
            p = d["_parent"]
            if p["kind"] == "trait": traits[p["name"]]["assoc"].append(d["name"])
    return gtypes, traits

def assoc_closure(traits, name, seen=None):
    seen = set() if seen is None else seen
    if name in seen or name not in traits: return set()
    seen.add(name)
    out = set(traits[name]["assoc"])
    for r in traits[name]["refines"]: out |= assoc_closure(traits, r, seen)
    return out

def refine_closure(traits, name, seen=None):
    seen = set() if seen is None else seen
    if name in seen: return seen
    seen.add(name)
    for r in traits.get(name, {}).get("refines", []): refine_closure(traits, r, seen)
    return seen

IDENT = re.compile(r"[A-Za-z_]\w*")
PATH = re.compile(r"^[A-Za-z_]\w*(\.[A-Za-z_]\w*)*$")

def classify(term, scope):
    """Returns (kind, root, depth) with kind in param / assoc / concrete / constructed."""
    t = term
    if t.startswith("<opaque"): return ("assoc", t.split(">")[0] + ">", 1)
    if PATH.match(t):
        comps = t.split(".")
        if comps[0] == "Swift" and len(comps) > 1: comps = comps[1:]
        root = comps[0]
        if root in scope["params"] or root == "Self":
            return ("param", root, 0) if len(comps) == 1 else ("assoc", root, len(comps) - 1)
        if root in scope["self_assoc"]:
            return ("assoc", "Self", len(comps))
        if root in scope["all_assoc"] and scope["in_type"] and root not in scope["types"]:
            return ("assoc", "Self", len(comps))
        return ("concrete", root, 0)
    ids = set(IDENT.findall(t))
    if ids & (scope["params"] | scope["self_assoc"] | {"Self"}): return ("constructed", "", 0)
    if scope["in_type"] and ids & (scope["all_assoc"] - scope["types"]): return ("constructed", "", 0)
    return ("concrete", "", 0)

def normal(term, scope):
    """A canonical spelling for union-find: bare associated types are prefixed with `Self.`."""
    k, root, depth = classify(term, scope)
    t = term[6:] if term.startswith("Swift.") else term
    if k == "assoc" and root == "Self" and not t.startswith("Self."): return "Self." + t
    return t

def shape_of(l, r):
    kl, kr = l[0], r[0]
    pair = tuple(sorted((kl, kr)))
    if pair == ("param", "param"): return "param == param"
    if pair == ("concrete", "param"): return "param == concrete"
    if pair == ("constructed", "param"): return "param == constructed"
    if pair == ("assoc", "concrete"): return "assoc == concrete"
    if pair == ("assoc", "constructed"): return "assoc == constructed"
    if pair == ("assoc", "param"): return "assoc == param"
    if pair == ("assoc", "assoc"):
        return "assoc == assoc (same root)" if l[1] == r[1] else "assoc == assoc (different roots)"
    return "other"

class UF:
    def __init__(self): self.p = {}
    def find(self, x):
        self.p.setdefault(x, x)
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]; x = self.p[x]
        return x
    def union(self, a, b): self.p[self.find(a)] = self.find(b)
    def classes(self):
        c = collections.defaultdict(list)
        for x in self.p: c[self.find(x)].append(x)
        return list(c.values())

def analyse(codebase, lang, decls, env_tables):
    gtypes, traits = tables(decls, lang)
    for g, t in env_tables:
        for k, v in g.items(): gtypes.setdefault(k, set()).update(v)
        for k, v in t.items(): traits.setdefault(k, v)
    all_assoc = set()
    for t in traits.values(): all_assoc.update(t["assoc"])
    type_names = set(gtypes) | set(traits)
    # requirements
    for d in decls:
        if lang == "rust": params, reqs = reqs_rust(d["generics"], d["where"], d["sig"], d["kw"])
        elif lang == "hylonew": params, reqs = reqs_hylonew(d["generics"], d["where"])
        else: params, reqs = reqs_swiftlike(d["generics"], d["where"], d["sig"], traits)
        if d["kind"] == "assoctype" and d["inherits"]:
            tmp = []
            if lang == "rust": rust_bounds(tmp, "Self." + d["name"], d["inherits"], "assocdecl")
            else:
                for part in split_top(d["inherits"], ","): add_bounds(tmp, "Self." + d["name"], part, "assocdecl", traits)
            reqs += tmp
        if d["kind"] == "trait" and lang == "swift": params = []      # primary associated types
        d["params"], d["reqs"], d["_traits"] = params, reqs, traits
    # scopes
    for d in decls:
        params, self_assoc, in_type, chain = set(), set(), False, []
        x = d
        while x is not None:
            chain.append(x)
            params.update(x["params"])
            k = x["kind"]
            if k in ("extension", "conformance", "type", "trait"):
                in_type = True
                nm = x["name"]
                base = re.match(r"[\w.:]*", nm).group(0)
                for comp in re.split(r"\.|::", base):
                    params.update(gtypes.get(comp, ()))
                last = re.split(r"\.|::", base)[-1] if base else ""
                if last in traits: self_assoc |= assoc_closure(traits, last)
                if lang == "rust" and k == "conformance":
                    tr = re.match(r"!?\s*([\w:]*)", x["inherits"]).group(1).split("::")[-1]
                    self_assoc |= assoc_closure(traits, tr)
            x = x["_parent"]
        scope = {"params": params, "self_assoc": self_assoc, "all_assoc": all_assoc, "types": type_names - all_assoc, "in_type": in_type}
        d["_scope"], d["_chain"] = scope, chain
        for r in d["reqs"]:
            if r["kind"] == "eq":
                l, rr = classify(r["lhs"], scope), classify(r["rhs"], scope)
                r["shape"] = shape_of(l, rr)
                r["depth"] = max(l[2], rr[2])
                r["nl"], r["nr"] = normal(r["lhs"], scope), normal(r["rhs"], scope)
            elif r["kind"] == "conf":
                k = classify(r["subj"], scope)
                r["subj_kind"] = k[0]
    # visible requirements (own and enclosing), equivalence classes, congruence closure
    for d in decls:
        vis = []
        for x in d["_chain"]: vis += x["reqs"]
        alleq = [r for r in vis if r["kind"] == "eq"]
        eqs = [r for r in alleq if r["via"] != "fnsugar"]       # `F: Fn(A) -> B` is a built-in arrow type in Hylo
        confs = [r for r in vis if r["kind"] == "conf"]
        d["n_vis_eq"], d["n_vis_conf"], d["n_vis_fnsugar"] = len(eqs), len(confs), len(alleq) - len(eqs)
        uf, edges = UF(), []
        for r in eqs:
            uf.union(r["nl"], r["nr"]); edges.append((r["nl"], r["nr"]))
        d["max_class_plain"] = max((len(c) for c in uf.classes()), default=0)
        members = {m for c in uf.classes() if len(c) > 1 for m in c}
        terms = set(members)
        for r in confs: terms.add(r["subj"])
        # weak criterion: a written projection `p.X` whose prefix `p` is equated to something
        weak = []
        for t in terms:
            if not PATH.match(t): continue
            comps = t.split(".")
            for k in range(len(comps) - 1, 0, -1):
                pre = ".".join(comps[:k])
                if pre in members: weak.append((pre, t)); break
        d["congruence_weak"] = sorted(set(weak))
        # strong criterion: congruence closure identifies two written terms that the written equalities do not
        merged = []
        changed = True
        while changed:
            changed = False
            canon = {}
            for t in sorted(terms):
                if not PATH.match(t): continue
                comps = t.split(".")
                for k in range(len(comps) - 1, 0, -1):
                    pre = ".".join(comps[:k])
                    if pre in uf.p and uf.find(pre) != pre:
                        c = uf.find(pre) + "." + ".".join(comps[k:])
                        other = canon.setdefault(c, t)
                        for o in ([other] if other != t else []) + ([c] if c in terms and c != t else []):
                            if uf.find(o) != uf.find(t):
                                uf.union(o, t); edges.append((o, t)); merged.append((o, t)); changed = True
                        break
        d["congruence"] = merged
        cls = [c for c in uf.classes() if len(c) > 1]
        d["classes"] = sorted((sorted(c) for c in cls), key=lambda c: -len(c))
        d["max_class"] = max((len(c) for c in cls), default=0)
        # longest chain: the largest number of equalities needed to relate two written terms
        adj = collections.defaultdict(set)
        for a, b in edges:
            if a != b: adj[a].add(b); adj[b].add(a)
        diam = 0
        for src in adj:
            dist, queue = {src: 0}, [src]
            for u in queue:
                for v in adj[u]:
                    if v not in dist: dist[v] = dist[u] + 1; queue.append(v)
            diam = max(diam, max(dist.values()))
        d["chain"] = diam
    return gtypes, traits

