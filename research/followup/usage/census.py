#!/usr/bin/env python3
"""Census of generic-programming features in Hylo, Swift and Rust sources.

usage:  python3 -I census.py [OUTDIR]

Reads the code bases listed in CODEBASES (the local compiler's standard library and tests, and the
sparse clones under ./clones), and writes into OUTDIR (default ./results):

  decls-<codebase>.jsonl   one record per declaration, with its classified requirements
  files-<codebase>.csv     per-file counts
  summary.json             the aggregated numbers
  tables.md                the same numbers as Markdown tables

The cloned sources are only read as text. Nothing in them is executed or imported.

METHOD AND LIMITS.  This is a lexical census, not a parser.  Comments and string literals are
blanked, declaration heads are found by keyword and delimited by bracket matching, and the generic
parameter list, the inheritance clause and the where clause are cut out of each head and split at
top-level commas.  Consequences:
  * A requirement is classified from its spelling.  A bare name is a generic parameter if an
    enclosing declaration (or the extended type) declares it, an associated type if the enclosing
    protocol/trait (or one it refines) declares it or if it is the name of an associated type
    somewhere in the code base, and a concrete type otherwise.  Type aliases are not expanded.
  * Requirements *implied* by a conformance (the requirement signature of the protocol) are not
    attached to the declaration; they are counted per protocol and added in a separate column.
  * Code generated by macros or templates (Swift .gyb files, Rust macro_rules!) is counted once, as
    written in the template, not once per expansion.
  * Conditional compilation branches are all counted.
  * Local functions are counted like any other function.
"""
