def blank(s):
    return "".join(c if c == "\n" else " " for c in s)

def strip_code(src, lang):
    """Returns `src` with comments and string literals blanked; offsets and newlines are kept."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        two = src[i:i + 2]
        if two == "//":
            j = src.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i)); i = j
        elif two == "/*":
            depth, j = 1, i + 2
            while j < n and depth:
                if src[j:j + 2] == "/*": depth += 1; j += 2
                elif src[j:j + 2] == "*/": depth -= 1; j += 2
                else: j += 1
            out.append(blank(src[i:j])); i = j
        elif lang == "swift" and src[i:i + 3] == '"""':
            j = src.find('"""', i + 3)
            j = n if j < 0 else j + 3
            out.append(blank(src[i:j])); i = j
        elif lang == "rust" and c == "r" and re.match(r'r#*"', src[i:i + 12]) and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == "_")):
            m = re.match(r'r(#*)"', src[i:i + 12])
            close = '"' + m.group(1)
            j = src.find(close, i + len(m.group(0)))
            j = n if j < 0 else j + len(close)
            out.append(blank(src[i:j])); i = j
        elif c == '"':
            j = i + 1
            multiline = lang == "rust"
            while j < n and src[j] != '"' and (multiline or src[j] != "\n"):
                j += 2 if src[j] == "\\" else 1
            j = min(n, j + 1)
            out.append(blank(src[i:j])); i = j
        elif lang == "rust" and c == "'":
            m = re.match(r"'(\\[^']*|[^\\'\n])'", src[i:i + 14])
            if m:
                out.append(" " * len(m.group(0))); i += len(m.group(0))
            else:
                out.append(c); i += 1
        else:
            out.append(c); i += 1
    return "".join(out)

def degyb(src):
    """Neutralises the template syntax of a Swift .gyb file."""
    lines = []
    for l in src.split("\n"):
        lines.append("" if l.lstrip().startswith("%") else l)
    return re.sub(r"\$\{[^}\n]*\}", "GYB", "\n".join(lines))

def match_braces(text):
    """Maps the offset of each '{' to the offset of its matching '}'."""
    stack, m = [], {}
    for i, c in enumerate(text):
        if c == "{": stack.append(i)
        elif c == "}" and stack: m[stack.pop()] = i
    return m

OPEN, CLOSE = "([<{", ")]>}"

def split_top(s, sep):
    """Splits `s` at the occurrences of `sep` that are not nested in brackets."""
    parts, depth, last, i, n = [], 0, 0, 0, len(s)
    while i < n:
        c = s[i]
        if s[i:i + 2] in ("->", "=>"): i += 2; continue
        if c in OPEN: depth += 1
        elif c in CLOSE: depth = max(0, depth - 1)
        elif depth == 0 and s.startswith(sep, i):
            if sep == "=" and (s[i:i + 2] == "==" or (i > 0 and s[i - 1] in "=!<>")):
                i += 1; continue
            if sep == ":" and (s[i:i + 2] == "::" or (i > 0 and s[i - 1] == ":")):
                i += 1; continue
            parts.append(s[last:i]); last = i + len(sep); i = last; continue
        i += 1
    parts.append(s[last:])
    return parts

def find_top(s, word):
    """Offset of the first top-level occurrence of the keyword `word` in `s`, or -1."""
    depth, i, n = 0, 0, len(s)
    while i < n:
        c = s[i]
        if s[i:i + 2] in ("->", "=>"): i += 2; continue
        if c in OPEN: depth += 1
        elif c in CLOSE: depth = max(0, depth - 1)
        elif depth == 0 and s.startswith(word, i) and (i == 0 or not (s[i - 1].isalnum() or s[i - 1] == "_")) \
                and (i + len(word) == n or not (s[i + len(word)].isalnum() or s[i + len(word)] == "_")):
            return i
        i += 1
    return -1

def angle_group(s, i):
    """`s[i]` is '<'.  Returns the offset just after the matching '>'."""
    depth, n = 0, len(s)
    while i < n:
        if s[i:i + 2] in ("->", "=>"): i += 2; continue
        if s[i] == "<": depth += 1
        elif s[i] == ">":
            depth -= 1
            if depth == 0: return i + 1
        i += 1
    return n

def paren_group(s, i):
    depth, n = 0, len(s)
    while i < n:
        if s[i] in "([": depth += 1
        elif s[i] in ")]":
            depth -= 1
            if depth == 0: return i + 1
        i += 1
    return n

def ws(s):
    return re.sub(r"\s+", " ", s).strip()

def nows(s):
    return re.sub(r"\s+", "", s)

# ------------------------------------------------------------------------------------------------
# Finding declaration heads
# ------------------------------------------------------------------------------------------------

KEYWORDS = {
    "swift": r"\b(func|init|subscript|struct|class|enum|protocol|extension|typealias|associatedtype|actor)\b",
    "hyloold": r"\b(fun|init|subscript|property|type|trait|extension|conformance|typealias|namespace)\b",
    "hylonew": r"\b(fun|init|subscript|struct|enum|trait|extension|given|type|typealias)\b",
    "rust": r"\b(fn|impl|trait|struct|enum|union|type)\b",
}
MODIFIERS = {
    "swift": set("public internal private fileprivate open package static class final override mutating nonmutating "
                 "required convenience indirect unowned weak lazy dynamic optional prefix postfix infix nonisolated "
                 "isolated consuming borrowing distributed __consuming __owned unsafe usableFromInline inline".split()),
    "hyloold": set("public internal private fileprivate static sink inout let set memberwise indirect".split()),
    "hylonew": set("public internal private module static sink inout let set memberwise indirect".split()),
    "rust": set("pub unsafe const async extern default safe auto".split()),
}
PREFIX = re.compile(r"^(?:\s*(?:@\w+(?:\((?:[^()]|\([^()]*\))*\))?|#\[[^\]]*\]|[A-Za-z_]\w*(?:\([\w: ]*\))?))*\s*$")
CONT_END = (",", "where", "->", ":", "==", "&", "=", "<", "(", "+", "is", "=>")
CONT_START = ("where", "->", ",", ":", "==", "&", "{", "=", "throws", "rethrows", "async", ")", ">", "+", "is", "=>", "for ")
TYPE_BRACE_PREV = (":", "->", "=>", "<", ",", "(", "==", "=", "&", "given", "[", "is", "...")

def prefix_ok(text, kw_start, lang):
    ls = text.rfind("\n", 0, kw_start) + 1
    pre = text[ls:kw_start]
    if not PREFIX.match(pre): return False
    for w in re.findall(r"(?<![@\w#\[])[A-Za-z_]\w*", re.sub(r"@\w+(\((?:[^()]|\([^()]*\))*\))?|#\[[^\]]*\]|\([\w: ]*\)", " ", pre)):
        if w not in MODIFIERS[lang]: return False
    return True

def head_end(text, i, lang):
    """Scans a declaration head from offset `i`.  Returns (offset, has_body)."""
    depth, n = 0, len(text)
    start = i
    while i < n:
        c = text[i]
        if c in "([": depth += 1
        elif c in ")]":
            depth -= 1
            if depth < 0: return i, False
        elif c == "{" and depth == 0:
            if lang in ("hylonew", "hyloold"):
                prev = text[start:i].rstrip()
                if prev.endswith(TYPE_BRACE_PREV) and not prev.endswith(("->>",)):
                    i = match_braces_from(text, i); continue       # a tuple type
            return i, True
        elif c == "}" and depth == 0: return i, False
        elif c == ";" and depth == 0: return i, False
        elif c == "\n" and depth == 0 and lang != "rust":
            prev = text[start:i].rstrip()
            rest = text[i:i + 400].lstrip()
            angle = prev.count("<") - prev.count(">") + prev.count("->") + prev.count("=>")
            if not (prev.endswith(CONT_END) or rest.startswith(CONT_START) or angle > 0):
                return i, False
        i += 1
    return n, False

def match_braces_from(text, i):
    depth, n = 0, len(text)
    while i < n:
        if text[i] == "{": depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0: return i + 1
        i += 1
    return n

TEXTS = collections.defaultdict(list)       # code base -> stripped texts, for the projection histogram

def scan_file(path, lang, codebase=None):
    src = open(path, encoding="utf-8", errors="replace").read()
    if path.endswith(".gyb"): src = degyb(src)
    text = strip_code(src, "swift" if lang.startswith("hylo") else lang)
    TEXTS[codebase].append(text)
    braces = match_braces(text)
    raw = []
    for m in re.finditer(KEYWORDS[lang], text):
        kw, s, e = m.group(1), m.start(), m.end()
        if not prefix_ok(text, s, lang): continue
        after = text[e:e + 40].lstrip()
        if lang == "swift":
            if kw == "class" and re.match(r"(func|var|let|subscript|init)\b", after): continue
            if kw == "init" and not re.match(r"[(?!<]", after): continue
            if kw in ("struct", "class", "enum", "protocol", "extension", "typealias", "associatedtype", "actor", "func") \
                    and not re.match(r"[A-Za-z_`\[]|[-+*/%<>=!&|^~?.]", after): continue
        if lang.startswith("hylo"):
            if kw == "init" and not re.match(r"[(<]", after):
                continue                                           # `memberwise init` and the like
            if kw == "type" and not re.match(r"[A-Za-z_]", after): continue
        if lang == "rust":
            if kw == "type" and not re.match(r"[A-Za-z_]", after): continue
            if kw in ("struct", "enum", "union", "trait", "fn") and not re.match(r"[A-Za-z_]", after): continue
            if kw == "union" and not re.match(r"[A-Za-z_]\w*\s*[<{]", after): continue
        he, has_body = head_end(text, e, lang)
        end = braces.get(he, he) if has_body else he
        raw.append({"kw": kw, "start": s, "head": text[e:he], "end": end, "line": text.count("\n", 0, s) + 1,
                    "has_body": has_body})
    # nesting
    stack = []
    for idx, d in enumerate(raw):
        while stack and raw[stack[-1]]["end"] < d["start"]: stack.pop()
        d["parent"] = stack[-1] if stack else None
        if d["has_body"]: stack.append(idx)
    return raw, text.count("\n") + 1

