def pct(xs, p):
    xs = sorted(xs)
    if not xs: return 0
    return xs[min(len(xs) - 1, int(round(p * (len(xs) - 1))))]

SHAPES = ["param == param", "param == concrete", "param == constructed", "assoc == concrete", "assoc == constructed",
          "assoc == param", "assoc == assoc (same root)", "assoc == assoc (different roots)", "other"]

def trait_signature(decls, traits):
    """Equalities and conformance requirements written inside each trait (on the trait and on its associated types)."""
    sig = collections.defaultdict(lambda: {"eq": 0, "conf": 0, "assoc": 0})
    for d in decls:
        owner = None
        if d["kind"] == "trait": owner = d["name"]
        elif d["kind"] == "assoctype" and d["_parent"] is not None and d["_parent"]["kind"] == "trait":
            owner = d["_parent"]["name"]; sig[owner]["assoc"] += 1
        if owner is None: continue
        sig[owner]["eq"] += sum(r["kind"] == "eq" for r in d["reqs"])
        sig[owner]["conf"] += sum(r["kind"] == "conf" for r in d["reqs"])
    return sig

def summarise(codebase, lang, decls, nlines, traits, env_sig):
    S = collections.OrderedDict()
    S["files"], S["lines"] = len(nlines), sum(nlines.values())
    by = collections.Counter(d["kind"] for d in decls)
    S["declarations"] = dict(by)
    def own(d, kind, vias=None): return [r for r in d["reqs"] if r["kind"] == kind and (vias is None or r["via"] in vias)]
    def is_generic(d):
        return bool(d["params"]) or (lang == "swift" and re.search(r"\bsome\s", d["sig"])) or (lang == "rust" and re.search(r"\bimpl\s", d["sig"]))
    gen = [d for d in decls if d["kind"] in ("function", "type", "alias", "extension", "conformance") and is_generic(d)]
    S["generic declarations"] = len(gen)
    S["generic functions"] = sum(d["kind"] == "function" for d in gen)
    S["generic types"] = sum(d["kind"] == "type" for d in gen)
    S["functions"] = by["function"]
    S["functions in a generic context"] = sum(1 for d in decls if d["kind"] == "function" and (d["_scope"]["params"] or d["_scope"]["self_assoc"]))
    S["where clauses"] = sum(bool(d["where"]) for d in decls)
    S["conformance requirements (where)"] = sum(len(own(d, "conf", ("where",))) for d in decls)
    S["conformance requirements (inline bounds)"] = sum(len(own(d, "conf", ("inline",))) for d in decls)
    S["conformance requirements (associated type declarations)"] = sum(len(own(d, "conf", ("assocdecl", "assocbound"))) for d in decls)
    S["inverse / lifetime / layout requirements"] = sum(len(own(d, "inverse")) + len(own(d, "lifetime")) + len(own(d, "layout")) for d in decls)
    eqs = [(d, r) for d in decls for r in d["reqs"] if r["kind"] == "eq"]
    S["equality requirements"] = len(eqs)
    S["equality requirements by origin"] = dict(collections.Counter(r["via"] for d, r in eqs))
    S["equality requirements by shape"] = {s: sum(r["shape"] == s for d, r in eqs) for s in SHAPES}
    S["equality requirements written in traits"] = sum(1 for d, r in eqs if d["kind"] in ("trait", "assoctype"))
    S["equality requirements by projection depth"] = dict(sorted(collections.Counter(r["depth"] for d, r in eqs).items()))
    S["declarations with an equality requirement"] = sum(1 for d in decls if own(d, "eq"))
    # conditional conformances and extensions
    def constrained(d): return any(r["kind"] in ("conf", "eq") for r in d["reqs"])
    ext = [d for d in decls if d["kind"] == "extension"]
    conf = [d for d in decls if d["kind"] == "conformance" or (d["kind"] == "extension" and d["inherits"])]
    S["extensions"] = len(ext)
    S["conformance declarations"] = len(conf) + sum(1 for d in decls if d["kind"] == "type" and d["inherits"] and lang != "rust")
    S["conformances declared (one per trait named)"] = sum(len([x for x in split_top(d["inherits"], "&" if lang == "hylonew" else ",") if ws(x)]) for d in conf) \
        + sum(len([x for x in split_top(d["inherits"], "&" if lang == "hylonew" else ",") if ws(x)]) for d in decls if d["kind"] == "type" and lang != "rust")
    S["conditional conformances"] = sum(constrained(d) for d in conf)
    def on_assoc(d): return any(r["kind"] == "conf" and r.get("subj_kind") == "assoc" for r in d["reqs"])
    S["conformance requirements on an associated type"] = sum(1 for d in decls if d["kind"] not in ("trait", "assoctype") for r in d["reqs"] if r["kind"] == "conf" and r.get("subj_kind") == "assoc")
    S["conditional conformances constraining an associated type"] = sum(on_assoc(d) or any(r["kind"] == "eq" for r in d["reqs"]) for d in conf)
    S["conditional extensions constraining an associated type"] = sum((on_assoc(d) or any(r["kind"] == "eq" for r in d["reqs"])) and not d["inherits"] for d in ext)
    S["conditional conformances with an equality"] = sum(any(r["kind"] == "eq" for r in d["reqs"]) for d in conf)
    S["conditional extensions"] = sum(constrained(d) and not d["inherits"] for d in ext)
    S["conditional extensions with an equality"] = sum(any(r["kind"] == "eq" for r in d["reqs"]) and not d["inherits"] for d in ext)
    def ext_of_trait(d):
        return re.split(r"\.|::", re.match(r"[\w.:]*", d["name"]).group(0))[-1] in traits
    S["extensions of a trait"] = sum(ext_of_trait(d) for d in ext)
    per_type = collections.Counter(re.match(r"[\w.:]*", d["name"]).group(0) or d["name"] for d in decls if d["kind"] in ("extension", "conformance"))
    S["types extended"] = len(per_type)
    S["extensions per type (median, p95, max)"] = [pct(per_type.values(), .5), pct(per_type.values(), .95), max(per_type.values(), default=0)]
    S["most extended"] = per_type.most_common(8)
    # traits
    tr = [d for d in decls if d["kind"] == "trait"]
    traits = dict(traits)
    own_assoc = collections.Counter(id(d["_parent"]) for d in decls if d["kind"] == "assoctype" and d["_parent"] is not None and d["_parent"]["kind"] == "trait")
    S["traits"] = len(tr)
    S["traits with associated types"] = sum(1 for d in tr if own_assoc[id(d)] > 0)
    S["traits with associated types (incl. inherited)"] = sum(1 for d in tr if own_assoc[id(d)] > 0 or assoc_closure(d["_traits"], d["name"]))
    S["associated types"] = sum(own_assoc.values())
    # overloads
    def container(d):
        path, x = [], d["_parent"]
        while x is not None:
            if x["kind"] in ("extension", "conformance", "type", "trait"):
                path.append(re.match(r"[\w.:]*", x["name"]).group(0) or x["name"])
                if x["kind"] in ("extension", "conformance"): break
            x = x["_parent"]
        pre = d["file"] + ":" if codebase in PER_FILE else ""
        return pre + (".".join(reversed(path)) if path else "<global>")
    fn = [d for d in decls if d["kind"] == "function" and d["name"]]
    per = collections.Counter((container(d), d["name"]) for d in fn)
    bare = collections.Counter((d["file"] + ":" if codebase in PER_FILE else "") + d["name"] for d in fn)
    S["function names (container, name)"] = len(per)
    S["overloaded function names (same container)"] = sum(v > 1 for v in per.values())
    S["largest overload sets (same container)"] = [[c + "." + n, v] for (c, n), v in per.most_common(6)]
    S["distinct bare function names"] = len(bare)
    S["bare names declared more than once"] = sum(v > 1 for v in bare.values())
    S["largest bare-name sets"] = bare.most_common(6)
    # requirement counts per declaration
    withreq = [d for d in decls if d["kind"] in ("function", "type", "alias", "extension", "conformance") and any(r["kind"] in ("conf", "eq") for r in d["reqs"])]
    n_req = [sum(r["kind"] in ("conf", "eq") for r in d["reqs"]) for d in withreq]
    witheq = [d for d in decls if d["kind"] in ("function", "type", "alias", "extension", "conformance") and own(d, "eq")]
    n_eq = [len(own(d, "eq")) for d in witheq]
    S["constrained declarations"] = len(withreq)
    S["requirements per constrained declaration (median, p95, p99, max)"] = [pct(n_req, .5), pct(n_req, .95), pct(n_req, .99), max(n_req, default=0)]
    S["declarations with equalities (excluding traits)"] = len(witheq)
    S["equalities per declaration that has one (median, p95, p99, max)"] = [pct(n_eq, .5), pct(n_eq, .95), pct(n_eq, .99), max(n_eq, default=0)]
    # what is visible in scope (own + enclosing declarations)
    body = [d for d in decls if d["kind"] == "function"]
    vis_all = [d["n_vis_eq"] + d["n_vis_conf"] for d in body]
    vis_eq = [d["n_vis_eq"] for d in body]
    S["local givens visible in a function (median, p95, p99, max)"] = [pct(vis_all, .5), pct(vis_all, .95), pct(vis_all, .99), max(vis_all, default=0)]
    S["local equalities visible in a function (median, p95, p99, max)"] = [pct(vis_eq, .5), pct(vis_eq, .95), pct(vis_eq, .99), max(vis_eq, default=0)]
    S["functions with a local equality in scope"] = sum(v > 0 for v in vis_eq)
    # implied by the traits named in the visible conformance requirements
    sig = trait_signature(decls, traits)
    for k, v in env_sig.items(): sig.setdefault(k, v)
    def implied(d):
        seen, n = set(), 0
        for x in d["_chain"]:
            pairs = [(r["subj"], r["bound"].split(".")[-1]) for r in x["reqs"] if r["kind"] == "conf"]
            if x["kind"] in ("extension", "trait"):
                last = re.split(r"\.|::", re.match(r"[\w.:]*", x["name"]).group(0))[-1]
                if last in traits: pairs.append(("Self", last))
            for subj, b in pairs:
                for t in refine_closure(traits, b):
                    if (subj, t) not in seen:
                        seen.add((subj, t)); n += sig[t]["eq"] if t in sig else 0
        return n
    imp = [implied(d) + d["n_vis_eq"] for d in body]
    S["equalities in scope incl. those of the named traits, one level (median, p95, p99, max)"] = [pct(imp, .5), pct(imp, .95), pct(imp, .99), max(imp, default=0)]
    S["functions with any equality in scope incl. those of the named traits"] = sum(v > 0 for v in imp)
    # transitivity and congruence
    alld = [d for d in decls if d["kind"] in ("function", "type", "alias", "extension", "conformance", "trait", "assoctype")]
    S["declarations whose visible equalities form a class of 3 or more terms"] = sum(d["max_class"] >= 3 for d in alld)
    S["largest equivalence class among visible equalities"] = max((d["max_class"] for d in alld), default=0)
    S["class sizes (declarations by largest class)"] = dict(sorted(collections.Counter(d["max_class"] for d in alld if d["max_class"] >= 2).items()))
    S["declarations needing a chain of 2 or more equalities"] = sum(d["chain"] >= 2 for d in alld)
    S["longest chain of equalities"] = max((d["chain"] for d in alld), default=0)
    S["chain lengths (declarations by longest chain)"] = dict(sorted(collections.Counter(d["chain"] for d in alld if d["chain"] >= 1).items()))
    S["declarations where a projection of an equated term is written"] = sum(bool(d["congruence_weak"]) for d in alld)
    S["declarations where congruence applies"] = sum(bool(d["congruence"]) for d in alld)
    S["declarations with equalities between different roots"] = sum(any(r["kind"] == "eq" and r["shape"] == "assoc == assoc (different roots)" for r in d["reqs"]) for d in alld)
    # projections written anywhere in the code (signatures and bodies): `X.A.B` where A, B name associated types
    all_assoc = set()
    for t in traits.values(): all_assoc.update(t["assoc"])
    hist = collections.Counter()
    if all_assoc:
        alt = "|".join(sorted(map(re.escape, all_assoc), key=len, reverse=True))
        sep = r"\s*::\s*" if lang == "rust" else r"\."
        rx = re.compile(r"(?<![\w.:])([A-Z]\w*)((?:%s(?:%s)\b)+)(?!\s*[(\w])" % (sep, alt))
        for text in TEXTS[codebase]:
            if lang == "rust":
                prev = None
                while prev != text:
                    prev = text
                    text = re.sub(r"<([^<>;{}]*?)\bas\b[^<>;{}]*(?:<[^<>;{}]*>)?\s*>\s*::", lambda m: m.group(1).strip() + "::", text)
            for m in rx.finditer(text):
                n = len(re.findall(sep, m.group(2))) + (1 if m.group(1) in all_assoc else 0)   # a bare associated type is `Self.A`
                hist[min(n, 4)] += 1
    S["projections written in the code, by depth (1, 2, 3, 4+)"] = [hist[1], hist[2], hist[3], hist[4]]
    S["trait signatures (trait: associated types, equalities, conformances)"] = {k: [v["assoc"], v["eq"], v["conf"]] for k, v in sorted(sig.items(), key=lambda kv: -kv[1]["eq"])[:12] if k in {d["name"] for d in tr}}
    return S, sig

def per_file(decls, nlines, lang):
    rows = []
    for f, n in sorted(nlines.items()):
        ds = [d for d in decls if d["file"] == f]
        eqs = [r for d in ds for r in d["reqs"] if r["kind"] == "eq"]
        row = collections.OrderedDict(file=f, lines=n, declarations=len(ds),
            generic=sum(1 for d in ds if d["params"] and d["kind"] in ("function", "type", "alias", "extension", "conformance")),
            where=sum(bool(d["where"]) for d in ds),
            conformance_reqs=sum(r["kind"] == "conf" for d in ds for r in d["reqs"]),
            equality_reqs=len(eqs))
        for s in SHAPES: row[s] = sum(r["shape"] == s for r in eqs)
        row["conditional_conformances"] = sum(1 for d in ds if (d["kind"] == "conformance" or (d["kind"] == "extension" and d["inherits"])) and any(r["kind"] in ("conf", "eq") for r in d["reqs"]))
        row["conditional_extensions"] = sum(1 for d in ds if d["kind"] == "extension" and not d["inherits"] and any(r["kind"] in ("conf", "eq") for r in d["reqs"]))
        row["extensions"] = sum(d["kind"] == "extension" for d in ds)
        row["conformance_decls"] = sum(1 for d in ds if d["kind"] == "conformance" or (d["kind"] in ("extension", "type") and d["inherits"] and lang != "rust"))
        row["traits"] = sum(d["kind"] == "trait" for d in ds)
        row["assoc_types"] = sum(d["kind"] == "assoctype" for d in ds)
        row["functions"] = sum(d["kind"] == "function" for d in ds)
        rows.append(row)
    return rows

