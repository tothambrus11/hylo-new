#!/usr/bin/env python3
"""Writes RESULTS.md from results.jsonl, orders.jsonl, localorders.jsonl and cost.jsonl."""
import glob, hashlib, json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
CONFIGS = ["base", "FULL", "FULL+sigrounds", "NOSIG", "NEW", "NEW+selfcheck"]
EXTRA = ["NEW-memberskip", "NEW-index", "NEW-absmodel", "NEW-extorder", "NEW-givencheck"]
NEWF = "FULL+sigrounds+assocsubst+eqindex+eqeager+premsubst+headsubst+abstractstrict"

def purpose(path):
    out = []
    for l in open(path):
        if not l.startswith("//"): break
        out.append(l[2:].strip())
    return " ".join(out).replace("|", "\\|")

def cell(r):
    if r is None: return "–"
    v = {"accept": "accept", "reject": "reject"}.get(r["verdict"], r["verdict"])
    if r["verdict"] == "reject": v += f" ({len(r['errors'])})"
    if r["violations"]: v += " **V**"
    return v

def main():
    latest = {}
    for l in open(os.path.join(HERE, "results.jsonl")):
        r = json.loads(l); latest[(r["program"], r["config"])] = r
    o = ["# Results", "",
         "One row per program of `p/`, one column per configuration (binary `eq22-554540c3a507`). "
         "`reject (n)` gives the number of diagnostics; **V** marks a `[selfcheck] VIOLATION` line; "
         "`rounds` is `sigrounds.rounds` under NEW. NOSIG is NEW without `sigrounds`; "
         "FULL+sigrounds is FULL with the single flag added. Raw data, with every diagnostic: `results.jsonl`. "
         "Generated by `tabulate.py`.", "",
         "| Program | " + " | ".join(CONFIGS) + " | rounds | What it tests |", "|---|" + "---|" * (len(CONFIGS) + 2)]
    interaction = []
    for path in sorted(glob.glob(os.path.join(HERE, "p", "*.hylo"))):
        name = os.path.relpath(path, HERE)
        sha = hashlib.sha1(open(path, "rb").read()).hexdigest()[:12]
        rs = {c: latest.get((name, c)) for c in CONFIGS + EXTRA}
        rs = {c: (r if r and r["sha"] == sha else None) for c, r in rs.items()}
        new = rs["NEW"]
        rounds = new["counters"].get("sigrounds.rounds", "") if new else ""
        o.append(f"| `{os.path.basename(name)[:-5]}` | " + " | ".join(cell(rs[c]) for c in CONFIGS) + f" | {rounds} | {purpose(path)} |")
        for c in EXTRA:
            if rs[c] and new: interaction.append((name, c, rs[c]["verdict"] == new["verdict"] and sorted(rs[c]["errors"]) == sorted(new["errors"])))
    o += ["", "## One flag removed from NEW", "",
          f"{len(set(n for n, _, _ in interaction))} programs were also run under NEW without `memberskip`, without `index`, without `absmodel`, "
          f"without `extorder` and without `givencheck` ({len(interaction)} runs). "
          f"Runs whose verdict or diagnostics differ from NEW: {sum(1 for x in interaction if not x[2])}.", ""]
    o += ["## Orders of the top-level declarations", "",
          "From `orders.jsonl` (written by `ord.py`, which calls `../sigrounds/orders.py`). An outcome is a verdict with its sorted diagnostics, "
          "positions removed, and the self-check lines.", "",
          "| Program | Configuration | Declarations (fixed) | Orders | Outcomes |", "|---|---|---|---|---|"]
    seen = {}
    for l in open(os.path.join(HERE, "orders.jsonl")):
        r = json.loads(l)
        if r.get("split"): seen[(r["file"], r["config"], r["fixed"])] = r
    for (f, c, fixed), r in sorted(seen.items()):
        prog = re.sub(r"\.[0-9a-f]{8}\.hylo$", "", os.path.basename(f))
        outs = "; ".join(f"{x['n']} {x['outcome']}" + (" **V**" if any("VIOLATION" in e for e in x["errors"]) else "") for x in r["outcomes"])
        o.append(f"| `{prog}` | {c.replace(NEWF, 'NEW')} | {r['decls']} ({fixed}) | {r['perms']} | {outs} |")
    o += ["", "## Orders of the declarations of a function body", "",
          "From `localorders.jsonl` (written by `localord.py`).", "",
          "| Program | Configuration | Local declarations | Orders | Outcomes |", "|---|---|---|---|---|"]
    seen = {}
    for l in open(os.path.join(HERE, "localorders.jsonl")):
        r = json.loads(l); seen[(r["file"], r["config"])] = r
    for (f, c), r in sorted(seen.items()):
        outs = "; ".join(f"{x['n']} {x['verdict']}" + (" **V**" if x["violations"] else "") for x in r["outcomes"])
        o.append(f"| `{os.path.basename(f)[:-5]}` | {c} | {r['decls']} | {r['perms']} | {outs} |")
    o += ["", "## Cost on generated programs", "",
          "From `cost.jsonl` (written by `cost.py`; programs in `cost/`). Counters of the user module. Times are indicative only: "
          "other jobs were running on the machine.", "",
          "| Shape | n | Configuration | Verdict | Nodes | Rounds | summon.calls | summon.matches | names.appliesCalls | type.user (ms) |", "|---|---|---|---|---|---|---|---|---|---|"]
    seen = {}
    for l in open(os.path.join(HERE, "cost.jsonl")):
        r = json.loads(l); seen[(r["shape"], r["n"], r["config"])] = r
    for (s, n, c), r in sorted(seen.items(), key=lambda x: (x[0][0], x[0][1], CONFIGS.index(x[0][2]))):
        o.append(f"| {s} | {n} | {c} | {r['verdict']} | {r.get('sigrounds.nodes', '')} | {r.get('sigrounds.rounds', '')} | {r.get('summon.calls', '')} | "
                 f"{r.get('summon.matches', '')} | {r.get('names.appliesCalls', '')} | {r.get('ms', '')} |")
    open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(o) + "\n")
    print(len(glob.glob(os.path.join(HERE, "p", "*.hylo"))), "programs")

if __name__ == "__main__":
    main()
